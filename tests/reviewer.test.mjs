import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {verifyReceipt} from '../reviewer/verifier.mjs';
const read=(p)=>JSON.parse(readFileSync(new URL(p,import.meta.url),'utf8'));
const fixture=read('../evidence/fixtures/synthetic-case-b.json');
const observed=read('../evidence/observed/ionq-simulator-case-b-2026-10-10.json');
const clone=o=>JSON.parse(JSON.stringify(o));
const alter=(f)=>{const x=clone(fixture);f(x);return x;};
test('synthetic fixture PASS',()=>assert.equal(verifyReceipt(fixture).status,'PASS'));
test('separable example has Z agreement',()=>assert.equal(verifyReceipt(fixture).computed.zz,1));
test('separable example has zero XX',()=>assert.equal(verifyReceipt(fixture).computed.xx,0));
test('fidelity claim is refutable',()=>assert.ok(verifyReceipt(fixture).computed.fidelityUpper<.9));
test('honest IonQ simulator receipt PASS',()=>assert.equal(verifyReceipt(observed).status,'PASS'));
test('IonQ measured ZZ matches counts',()=>assert.equal(verifyReceipt(observed).computed.zz,.984375));
test('IonQ measured XX matches counts',()=>assert.equal(verifyReceipt(observed).computed.xx,-.046875));
test('IonQ claim-specific bound below threshold',()=>assert.ok(verifyReceipt(observed).computed.fidelityUpper<.90));
test('forged witness S fails',()=>assert.equal(verifyReceipt(alter(x=>x.evidence.S=2)).status,'FAIL'));
test('false decision support fails',()=>assert.equal(verifyReceipt(alter(x=>x.decision.supported=false)).status,'FAIL'));
test('changed qubit count fails',()=>assert.equal(verifyReceipt(alter(x=>x.execution.qubits=5)).status,'FAIL'));
test('changed shot count fails',()=>assert.equal(verifyReceipt(alter(x=>x.configuration.shots=512)).status,'FAIL'));
test('malformed bitstrings fail',()=>assert.equal(verifyReceipt(alter(x=>x.execution.rawCounts={'NOT-BITS':128})).status,'FAIL'));
test('extra quantum job fails',()=>assert.equal(verifyReceipt(alter(x=>x.events.push({type:'LIVE_QUANTUM_RUN_COMPLETED',utc:'2026-10-10T00:00:03Z'}))).status,'FAIL'));
test('invalid JSON fails safely',()=>assert.equal(verifyReceipt('invalid json').status,'FAIL'));
